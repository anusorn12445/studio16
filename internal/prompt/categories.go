// CategoryPromptList merges the built-in defaults with saved overrides, returning
// one entry per category with its effective prompt and whether it was edited.
func CategoryPromptList(overrides map[string]string) []map[string]any {
	out := make([]map[string]any, 0, len(CategoryPrompts))
	for _, c := range CategoryPrompts {
		p := c.Prompt
		custom := false
		if v, ok := overrides[c.Category]; ok && v != "" {
			p = v
			custom = true
		}
		out = append(out, map[string]any{
			"category": c.Category,
			"group":    c.Group,
			"label":    c.Label,
			"prompt":   p,
			"default":  c.Prompt,
			"custom":   custom,
		})
	}
	return out
}
